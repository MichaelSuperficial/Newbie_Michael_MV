choice = input("Куда поедет витязь? (прямо / направо / налево): ").strip().lower()

if choice == "прямо":
    print("Витязь поехал прямо — и сгинул в бою. Живу не бывать.")
elif choice == "направо":
    print("Витязь поехал направо — коня потерял, но сам остался жив.")
elif choice == "налево":
    print("Витязь поехал налево — и женился. Счастье нашёл, да не в бою.")
else:
    print("Стоит витязь на распутье и не знает, куда ехать.")
